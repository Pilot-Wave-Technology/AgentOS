class AgentCreateRequest(BaseModel):
    """Request model for POST /api/v1/agents (JSON API)."""
    id: str
    name: str
    type: Literal["SHCA", "IA", "GO", "RA"] = "SHCA"
    scope: Literal["goal", "task"] = "task"
    model: str = "google/gemini-2.5-flash"
    emoji: str = ""
    base_system_prompt: str = ""
    soul: str = ""
    tools_allow: list[str] = []
    tools_deny: list[str] = []
    memory_enabled: bool = False
    max_tokens: Optional[int] = None
    notes: str = ""
    files: dict[str, str] = {}
    # Links to a template so provision_agent can expand that template's tool profiles.
    # If None, tools_allow is used directly with no profile expansion.
    template_id: Optional[str] = None


class AgentUpdateRequest(BaseModel):
    """Request model for PATCH /api/v1/agents/{id} — all fields optional."""
    name: Optional[str] = None
    type: Optional[Literal["SHCA", "IA", "GO", "RA"]] = None
    scope: Optional[Literal["goal", "task"]] = None
    model: Optional[str] = None
    emoji: Optional[str] = None
    base_system_prompt: Optional[str] = None
    soul: Optional[str] = None
    tools_allow: Optional[list[str]] = None
    tools_deny: Optional[list[str]] = None
    memory_enabled: Optional[bool] = None
    max_tokens: Optional[int] = None
    notes: Optional[str] = None
    files: Optional[dict[str, str]] = None    # only provided keys are updated


class AgentCreate(BaseModel):
    id: str                          # unique slug e.g. ia-researcher
    name: str
    type: Literal["SHCA", "IA", "GO", "RA"] = "SHCA"
    scope: Literal["goal", "task"] = "task"
    model: str = "google/gemini-2.5-flash"
    emoji: str = ""
    base_system_prompt: str = ""     # Written to AGENTS.md on creation
    soul: str = ""                   # Written to SOUL.md on creation
    tools_allow: list[str] = []
    tools_deny: list[str] = []
    memory_enabled: bool = False
    max_tokens: Optional[int] = None
    notes: str = ""


class Agent(AgentCreate):
    created_at: Optional[datetime] = None
    status: Literal["active", "deleted"] = "active"
    gateway_agent_id: str = ""       # ID returned by agents.create
    workspace: str = ""              # Workspace path on the VM


class AgentContextCreate(BaseModel):
    additional_instructions: str = ""
    skills: list[str] = []


class AgentContext(AgentContextCreate):
    agent_id: str
    goal_id: str
    workspace_files: list[str] = []   # GCS URIs
    added_at: Optional[datetime] = None
    added_by: str = ""
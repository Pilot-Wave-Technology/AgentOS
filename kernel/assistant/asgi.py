"""The same surface, mounted on the control panel's own app.

`api.py` serves these tools from a standalone ThreadingHTTPServer on its
own port. That is right for E0 and for the gates, and it CANNOT DEPLOY:
Cloud Run gives a container one port, so a second server on 8790 is
unreachable from anywhere. The gateway would be pointed at a URL nothing
answers.

So the cloud transport is a router on the control panel's existing app,
and `KERNEL_ASSISTANT_URL` becomes the control panel's own base URL
rather than a localhost port that only exists on a laptop.

ONE SET OF HANDLERS, TWO TRANSPORTS. The routes here are GENERATED by
iterating `ROUTES` and `GO_ROUTES` and both call the same `_dispatch`
and `_dispatch_go` as the standalone server. Writing them out by hand
would create a third place the tool surface is declared -- and this
project has spent the week finding the first two: the tools drifted from
the TypeScript, the routes from the tools, and the prompt from the
database. A surface that is enumerated cannot drift from itself.

WHAT STAYS THE SAME ACROSS BOTH. GET for reads and POST for writes,
because a GET that changes something is invisible to every proxy and
retry policy that assumes otherwise. A typed refusal is 200 with a
`refused` code, never a 4xx, because it is a result the assistant reads
and an error status invites the gateway's retry logic to bury it.
"""

# NO `from __future__ import annotations` HERE, deliberately.
#
# FastAPI resolves a handler's annotations through get_type_hints, which
# looks in the function's MODULE globals. With postponed evaluation the
# `Request` annotation stays a string, and `Request` is a local of
# build_router now -- so the module imported fine, the module-load gate
# went green, and mounting the router died with
# `PydanticUndefinedAnnotation: name 'Request' is not defined`.
#
# Evaluated eagerly, the annotation resolves against the enclosing scope
# at def time and FastAPI gets the class itself.

import logging
import os
from contextlib import asynccontextmanager

from kernel.assistant.api import (GO_ROUTES, OPEN_ENV, ROUTES, _dispatch,
                                  _dispatch_go, _require_auth_decision,
                                  _token, route_table)
from kernel.assistant.context import Refused

logger = logging.getLogger(__name__)


def _payload(out) -> dict:
    if isinstance(out, Refused):
        return {"refused": out.code, "detail": out.message,
                "candidates": list(out.candidates)}
    return out


# Machine-to-machine traffic lives under /internal on this app, which is
# how the control panel already separates "a browser with a session"
# from "another service with a token" -- for auth, for logging, and for
# anything that fronts it. The gateway's KERNEL_ASSISTANT_URL carries
# the prefix as part of the base URL, so the tool code builds the same
# `<base>/assistant/<goal>/<tool>` path in both deployments and needs no
# knowledge of which one it is talking to.
CLOUD_PREFIX = "/internal/kernel"

# ── WHICH DATABASE THE KERNEL SCHEMA IS IN ───────────────────────────
#
# The same database as the control panel's -- there is only one now --
# but NOT the same pool, and the difference is search_path.
#
# Kernel objects live in a `kernel` schema, so these queries need
# search_path = kernel, public. The control panel's pool must not have
# that: an unqualified `executions` would then resolve differently
# depending on which pool a query happened to borrow, which is a bug
# that reads as flakiness.
#
# It was briefly two servers, and handing this router the control
# panel's pool did not fail on a missing table -- it silently queried
# the other `goal_resources` and came back `UndefinedColumnError:
# column r.resource_id does not exist`. That is what the consolidation
# fixed; this variable is what keeps the schema path explicit.
KERNEL_DSN_ENV = "KERNEL_DATABASE_URL"


# The search_path the kernel's unqualified table names need. Spelled
# once: both branches of kernel_acquire set it, and they must agree.
KERNEL_SEARCH_PATH = "kernel,public"


def kernel_acquire(fallback):
    """An `acquire` for the kernel schema, however it is deployed.

    TWO DEPLOYMENTS, AND THE FALLBACK USED TO BREAK THE COMMON ONE.

    With a separate DSN this builds its own pool carrying
    search_path=kernel,public. Without one it borrows the caller's pool
    -- and it used to hand that back UNTOUCHED, on a docstring that said
    "one database with a `kernel` schema is the expected cloud shape".
    It is, and that is exactly the shape the untouched pool cannot
    serve: the control panel's pool resolves `public`, the kernel's
    tables are in `kernel`, and every tool answered

        UndefinedTableError: relation "assistant_requests" does not exist

    while the schema sat there with 31 tables in it. A fallback whose
    comment names a case it does not handle is worse than no fallback.

    SET AND RESET, rather than leaving it on. The whole reason this
    function exists is the note below: the control panel's pool must not
    carry `kernel` on its path, or an unqualified `executions` resolves
    differently depending on which pool a query happened to borrow --
    flakiness, not an error. A pooled connection is held exclusively for
    the life of the `async with`, so setting it on acquire and putting
    it back on release is invisible to every other borrower.
    """
    dsn = (os.environ[KERNEL_DSN_ENV]
           if KERNEL_DSN_ENV in os.environ else "").strip()
    if not dsn:
        @asynccontextmanager
        async def borrowed():
            async with fallback() as conn:
                await conn.execute(f"SET search_path = {KERNEL_SEARCH_PATH}")
                try:
                    yield conn
                finally:
                    # Never let the reset be the thing that fails the
                    # request: a connection that died mid-tool is
                    # discarded by the pool anyway, and re-raising here
                    # would replace a real error with a confusing one.
                    try:
                        await conn.execute("RESET search_path")
                    except Exception:                       # noqa: BLE001
                        logger.warning(
                            "kernel surface: could not reset search_path")
        return borrowed

    holder: dict = {}

    @asynccontextmanager
    async def acquire():
        if "pool" not in holder:
            import asyncpg
            holder["pool"] = await asyncpg.create_pool(
                dsn, min_size=1, max_size=4,
                server_settings={"search_path": KERNEL_SEARCH_PATH})
            logger.info("kernel surface: own pool for the kernel schema")
        async with holder["pool"].acquire() as conn:
            yield conn

    return acquire


def build_router(acquire, prefix: str = CLOUD_PREFIX):
    """Build the router. FastAPI is imported HERE, not at module scope.

    The E0 container runs the kernel and serves nothing over HTTP, so it
    has no web framework -- and a module-level import made this the one
    module of 137 that would not load there. The module-load gate was
    right to fail; adding an exemption would have been the wrong fix,
    because an exemption list is a place defects go to live.
    """
    """A router over the kernel tool surface.

    `acquire` is a zero-argument callable returning an async context
    manager yielding a connection -- normally `pool.acquire`. Passed in
    rather than imported so the control panel decides which database
    the kernel schema lives in, which is the one thing that genuinely
    differs between a laptop and a deployment.
    """
    from fastapi import APIRouter, Request  # noqa: PLC0415

    # ── THE GUARD THE OTHER TRANSPORT HAS ───────────────────────────
    #
    # api.py refuses to START without ASSISTANT_API_TOKEN, and says why:
    # this surface carries start_story, steer, amend, cancel_story and
    # every GO write, addressed by a goal id in the path with no other
    # scoping, so an unauthenticated one lets any caller drive any goal.
    #
    # That check was wired into the ThreadingHTTPServer -- the transport
    # that only ever runs on a laptop -- and NOT into this one, which is
    # the transport that gets a public Cloud Run URL. So the deployment
    # the rule was written for was the deployment without it, and the
    # surface came up open: 37 tools, no auth, on the internet.
    #
    # Raising here means the router does not mount. app/main.py catches
    # that and serves the control panel without the kernel tools, which
    # is the right trade: an assistant that reports E_KERNEL_UNREACHABLE
    # is legible, and an open write surface is not.
    # OPEN_ENV, not the name spelled out again. The flag's whole design
    # is that finding it in a process environment is finding the answer,
    # and a second spelling here is one grep away from not matching.
    if _require_auth_decision():
        logger.warning(
            "kernel surface is OPEN (%s=1): any caller that can reach "
            "this app can start, steer and cancel work on any goal",
            OPEN_ENV)

    router = APIRouter(prefix=prefix, tags=["kernel-assistant"])

    def register(method: str, path: str, who: str, tool: str) -> None:
        is_read = method == "GET"

        async def endpoint(goal: str, request: Request):
            want = _token()
            if want and request.headers.get("X-Assistant-Token") != want:
                return {"refused": "E_UNAUTHORISED"}
            actor = request.headers.get("X-Assistant-Actor") or who
            if is_read:
                args = dict(request.query_params)
            else:
                try:
                    args = await request.json()
                except Exception:                          # noqa: BLE001
                    args = {}
            try:
                async with acquire() as conn:
                    out = await (_dispatch_go if who == "go" else _dispatch)(
                        conn, tool, goal, actor, args or {})
            except Exception as e:                          # noqa: BLE001
                logger.exception("kernel surface: %s", tool)
                return {"refused": "E_TOOL_FAILED",
                        "detail": f"{type(e).__name__}: {e}"}
            return _payload(out)

        endpoint.__name__ = f"{who}_{tool}"
        router.add_api_route(path, endpoint, methods=[method])

    # Derived, never restated. route_table() is the single description
    # both transports read.
    for row in route_table():
        register(*row)

    logger.info("kernel surface mounted at %s: %d assistant + %d go tools",
                prefix or "/", len(ROUTES), len(GO_ROUTES))
    return router
